#!/usr/bin/env node
// One-off: turn the Sites export (stackd-export.json) into SQL for the new D1.
//
//   node scripts/seed-from-export.mjs template <export.json> > mapping.json
//       Writes { "<account id>": { "name", "code", "email": "" } } for you to fill in.
//   node scripts/seed-from-export.mjs sql <export.json> <mapping.json> > seed.sql
//       Validates the mapping and prints INSERTs (parents before children).
//   npx wrangler d1 execute DB --remote --file seed.sql
//
// Keep the export, mapping and seed.sql outside the repository: they hold real ledgers.
import { readFileSync } from 'node:fs';

const [mode, exportPath, mappingPath] = process.argv.slice(2);
const usage = () => { console.error('Usage: seed-from-export.mjs template <export.json> | sql <export.json> <mapping.json>'); process.exit(2); };
if (!exportPath || !['template', 'sql'].includes(mode)) usage();

const data = JSON.parse(readFileSync(exportPath, 'utf8'));
const t = data.tables;
for (const name of ['accounts', 'profiles', 'sessions', 'players', 'entries', 'friendships']) {
  if (!Array.isArray(t?.[name])) throw new Error(`Export is missing table ${name}.`);
}

if (mode === 'template') {
  const out = Object.fromEntries(t.accounts.map(a => [a.id, { name: a.name, code: a.code, email: '' }]));
  process.stdout.write(JSON.stringify(out, null, 2) + '\n');
  process.exit(0);
}

if (!mappingPath) usage();
const mapping = JSON.parse(readFileSync(mappingPath, 'utf8'));
const emailById = new Map();
const seen = new Map();
const problems = [];
for (const [id, entry] of Object.entries(mapping)) {
  if (!t.accounts.some(a => a.id === id)) problems.push(`Mapping names unknown account ${id}.`);
  const email = String(entry?.email ?? '').trim().toLowerCase();
  if (!email) continue; // Unmapped accounts stay unclaimable until an email is added.
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) problems.push(`Account ${id} (${entry.name}) has an invalid email "${email}".`);
  if (seen.has(email)) problems.push(`Email ${email} is mapped to both ${seen.get(email)} and ${id}.`);
  seen.set(email, id);
  emailById.set(id, email);
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const q = v => v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`;
const insert = (table, rows, cols) => rows.map(r => `INSERT INTO ${table} (${cols.join(',')}) VALUES (${cols.map(c => q(r[c])).join(',')});`);

const lines = [
  '-- Generated by scripts/seed-from-export.mjs. Do not commit.',
  `-- Source export: ${data.exportedAt ?? 'unknown time'}`,
  'PRAGMA defer_foreign_keys = true;',
  ...insert('accounts', t.accounts.map(a => ({ ...a, email: emailById.get(a.id) ?? null })), ['id', 'name', 'code', 'email']),
  ...insert('profiles', t.profiles, ['owner', 'name', 'currency']),
  ...insert('sessions', t.sessions, ['id', 'owner', 'title', 'mode', 'venue', 'game', 'stakes', 'notes', 'currency', 'start', 'end', 'status', 'revision', 'last_write', 'invite_token']),
  ...insert('players', t.players, ['id', 'session_id', 'name', 'is_self', 'cashout', 'account_id']),
  ...insert('entries', t.entries, ['id', 'session_id', 'player_id', 'kind', 'amount', 'at']),
  ...insert('friendships', t.friendships, ['id', 'a', 'b', 'requested_by', 'status']),
];
process.stdout.write(lines.join('\n') + '\n');
const counts = ['accounts', 'profiles', 'sessions', 'players', 'entries', 'friendships'].map(n => `${n}=${t[n].length}`).join(' ');
console.error(`Seed SQL ready: ${counts}; ${emailById.size} of ${t.accounts.length} accounts mapped to an email.`);
